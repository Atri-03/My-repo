class UnitTestRunCreate(BaseModel):
    tenant_id: Optional[str] = None
    object_name: str
    object_type: str
    test_classes: Optional[List[str]] = None


class UnitTestRunRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    tenant_id: str
    object_name: str
