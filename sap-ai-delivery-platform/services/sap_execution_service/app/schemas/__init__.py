# ---------------------------------------------------------------------------
# SAP Solution Architect Agent - execution planning
# ---------------------------------------------------------------------------
class ExecutionPlanCreate(BaseModel):
    tenant_id: Optional[str] = None
    technical_specification_id: str
    package_name: Optional[str] = None
    needs_cds: Optional[bool] = False
    needs_rap: Optional[bool] = False
    needs_odata: Optional[bool] = False
    object_names: Optional[List[str]] = None


class ExecutionPlanRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    tenant_id: str
    technical_specification_id: str
    package_name: Optional[str] = None
    transport_description: Optional[str] = None
    steps: List[Dict[str, Any]]
    status: str
    created_at: Optional[datetime] = None
